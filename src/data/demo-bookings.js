import { addLocalDays } from "@/lib/date";
import { buildScheduledStops } from "@/lib/itinerary-engine";
import {
  CHECK_IN_METHODS,
  addMinutesToClock,
  deriveCheckpointType,
  evaluatePunctuality,
} from "@/lib/punctuality";

const DEMO_SOURCE = "PRESENTATION_DEMO";
const OPERATIONAL_STATUSES = new Set([
  "CONFIRMED",
  "GUIDE_ASSIGNED",
  "READY",
  "IN_PROGRESS",
  "COMPLETED",
  "INFORMATION_REQUIRED",
  "CHANGE_REQUESTED",
]);

function buildItinerary(arrivalDate, itineraryMatrix) {
  return itineraryMatrix.map((destinationIds, index) => ({
    dayNumber: index + 1,
    date: addLocalDays(arrivalDate, index),
    destinationIds,
    estimatedMinutes: destinationIds.length * 120,
    scheduledStops: buildScheduledStops(destinationIds),
  }));
}

function buildDemoBooking({
  id,
  reference,
  createdAt,
  arrivalDate,
  departureDate,
  adults,
  children = 0,
  nationality,
  preferredLanguage,
  preferredTierId,
  recommendedTierId,
  selectedTierId,
  tierMatchScore,
  tierRecommendationReasons,
  eligibleTierIds,
  tierIneligibilityReasons = {},
  smallGroupSupplementApplied = false,
  guidesRequired,
  multilingualRequired,
  partyBusRequired = false,
  pickupIncluded = false,
  selectedDestinationIds,
  itineraryMatrix,
  hotelId = "",
  arrivalOption,
  arrivalDetails,
  traveller,
  pricingBreakdown,
  estimatedTotalMYR,
  totalNights,
  status,
  assignedGuideIds = [],
  assignedPartyBusId = "",
  customerFeedback = [],
  serviceCheckpoints = null,
}) {
  const checkpointTime = arrivalDetails?.arrivalTime || "09:00";
  const defaultMinutesVariance = (Number(reference.slice(-2)) % 5) * 4 - 8;
  const actualCheckInTime = OPERATIONAL_STATUSES.has(status) && assignedGuideIds.length
    ? addMinutesToClock(checkpointTime, defaultMinutesVariance)
    : "";
  const punctuality = evaluatePunctuality(checkpointTime, actualCheckInTime);
  const generatedCheckpoints = serviceCheckpoints === null
    ? assignedGuideIds.map((guideId, index) => ({
        id: `${id}-checkpoint-${index + 1}`,
        checkpointType: deriveCheckpointType(arrivalOption),
        scheduledMeetupTime: checkpointTime,
        scheduledMeetupLocation:
          arrivalOption === "KLIA"
            ? arrivalDetails?.terminal || "KLIA arrival hall"
            : arrivalOption === "ETS"
              ? "Ipoh ETS station"
              : "Trip day meetup point",
        guideId,
        guideCheckInTime: actualCheckInTime,
        guideCheckInMethod: CHECK_IN_METHODS.ADMIN_MANUAL_UPDATE,
        customerArrivalConfirmedTime: actualCheckInTime,
        adminVerifiedTime: actualCheckInTime ? `${arrivalDate}T${actualCheckInTime}:00.000Z` : "",
        punctualityStatus: punctuality.status,
        minutesEarlyLate: punctuality.minutesEarlyLate,
        punctualityNote: actualCheckInTime
          ? "Recorded from presentation demo checkpoint data."
          : "Awaiting day-of-service check-in.",
      }))
    : serviceCheckpoints;
  const generatedFeedback = customerFeedback.length
    ? customerFeedback
    : assignedGuideIds.map((guideId) => ({
        guideId,
        rating: status === "COMPLETED" ? 4.8 : status === "IN_PROGRESS" ? 4.7 : 4.6,
        complaintCount: status === "CHANGE_REQUESTED" || status === "INFORMATION_REQUIRED" ? 1 : 0,
        repeatRequest: status === "COMPLETED" && Number(reference.slice(-1)) % 2 === 0,
        comment:
          status === "COMPLETED"
            ? "Guide handled the trip smoothly and communicated clearly."
            : status === "IN_PROGRESS"
              ? "Traveller feedback is positive so far."
              : "Customer feedback pending final trip completion.",
        submittedAt: `${arrivalDate}T18:00:00.000Z`,
      }));

  return {
    id,
    reference,
    createdAt,
    arrivalDate,
    departureDate,
    adults,
    children,
    childrenAges: [],
    nationality,
    preferredLanguage,
    preferredTierId,
    recommendedTierId,
    selectedTierId,
    tierMatchScore,
    tierRecommendationReasons,
    eligibleTierIds,
    tierIneligibilityReasons,
    smallGroupSupplementApplied,
    guidesRequired,
    multilingualRequired,
    partyBusRequired,
    pickupIncluded,
    selectedDestinationIds,
    recommendedItinerary: buildItinerary(arrivalDate, itineraryMatrix),
    hotelId,
    arrivalOption,
    arrivalDetails,
    traveller,
    pricingBreakdown,
    priceBreakdown: pricingBreakdown,
    estimatedTotalMYR,
    totalMYR: estimatedTotalMYR,
    totalNights,
    estimatedTotalLabel: "Estimated Total",
    status,
    assignedGuideId: assignedGuideIds[0] || "",
    assignedGuideIds,
    assignedPartyBusId,
    customerFeedback: generatedFeedback,
    serviceCheckpoints: generatedCheckpoints,
    source: DEMO_SOURCE,
  };
}

